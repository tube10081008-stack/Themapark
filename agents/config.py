def pricing_note() -> str:
    """요금 확정 여부에 따라 프롬프트에 붙일 안내 문구를 만든다."""
    fixed = {k: v for k, v in PRICING.items() if v is not None}
    if not fixed:
        return "\n# 요금\n아직 확정되지 않았습니다. 요금을 언급해야 할 경우 '확정 후 안내 예정'이라고만 쓰십시오.\n"
    lines = "\n".join(f"- {k}: {v:,}원" for k, v in fixed.items())
    return f"\n# 요금 (2시간 기준)\n{lines}\n"


def operations_note() -> str:
    return (
        f"\n# 운영 정보\n"
        f"- 운영시간: {OPERATING_HOURS}\n"
        f"- 휴무일: {CLOSED_DAYS}\n"
        f"- 예약: {RESERVATION_URL or '확정 후 안내 예정'}\n"
        f"- 문의 전화: {PHONE or '확정 후 안내 예정'}\n"
    )


def system_prompt() -> str:
    """캐시 대상이 되는 전체 시스템 프롬프트."""
    return FACILITY_CONTEXT + pricing_note() + operations_note()
